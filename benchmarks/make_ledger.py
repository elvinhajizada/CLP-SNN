"""
Number ledger for the NMI manuscript: the single source of every cost number.

Reads benchmarks/reports_table1.csv (written by generate_table_results.py) and
writes a markdown ledger plus a flat CSV. Constants that are not in the reports
(Loihi row, accuracies, extractor costs) are declared at the top with their
provenance. Re-run this after any re-benchmark; never edit the outputs by hand.

Usage:
  python benchmarks/make_ledger.py --table1 benchmarks/reports_table1.csv \
      --out "<folder>/numbers.md"
"""
import argparse
import datetime as dt
import os

import pandas as pd

# ---------------------------------------------------------------------------
# Constants with provenance (everything not produced by the Orin harness)
# ---------------------------------------------------------------------------

# Loihi 2 per-sample OCL step, unchanged from the round-2 manuscript Table 1.
LOIHI = {"lat_ms": 0.33, "tot_mJ": 0.05, "dyn_mJ": 0.01}

# Final accuracy, mean +/- std over 3 class orders (round-2 Table 1; SLDA from
# the rank-one runs, E-A, nmi-manuscript-integration.md section 2).
ACC = {
    "CLP-SNN":    ((55.4, 2.5), (90.0, 0.4)),
    "CLP":        ((57.0, 2.4), (93.0, 0.2)),
    "ncm":        ((53.1, 2.9), (84.5, 0.8)),
    "replay":     ((55.1, 2.5), (91.6, 0.4)),
    "SLDA-rank1": ((54.8, 2.5), (96.2, 0.1)),
    "SLDA-naive-rho1": ((54.4, 2.3), (95.7, 0.2)),   # Hayes shrinkage variant, SI only
}

# EfficientNet-B0 extractor on the Orin GPU, TensorRT batch 1 (tab:fe_benchmark).
FE = {
    "FP32": {"lat_ms": 4.8, "tot_mJ": 45.3, "dyn_mJ": 24.0},
    "FP16": {"lat_ms": 3.2, "tot_mJ": 26.5, "dyn_mJ": 12.4},
    "INT8": {"lat_ms": 2.4, "tot_mJ": 17.5, "dyn_mJ": 6.7},
}

# Composition rule (cheapest correct implementation of the test-then-train step):
# the update pass of these methods already produces the prediction, so the step
# cost is the update alone. All other methods: step = update + query.
SINGLE_PASS = {"CLP", "replay"}

DISPLAY = {"CLP-SNN": "CLP-SNN", "CLP": "CLP", "ncm": "NCM", "replay": "Replay",
           "SLDA-rank1": "SLDA (rank-one)",
           "SLDA-naive-rho1": "SLDA (naive, per-sample inversion)"}
DEVICE = {"orin-gpu": "GPU", "orin-cpu": "CPU"}
MAIN_ORDER = ["CLP", "ncm", "replay", "SLDA-rank1"]
KEYS = ("lat_ms", "tot_mJ", "dyn_mJ")


def r(x, nd=2):
    return f"{x:.{nd}f}"


def ratio(x):
    return f"{x:.1f}x" if x < 10 else f"{x:.0f}x"


def compose(row):
    """Step cost under the composition rule."""
    single = row["Method"] in SINGLE_PASS

    def pick(upd, qry):
        return upd if single else upd + qry

    return {
        "lat_ms": pick(row["C_upd Latency (ms)"], row["C_qry Latency (ms)"]),
        "tot_mJ": pick(row["C_upd Total E (mJ)"], row["C_qry Total E (mJ)"]),
        "dyn_mJ": pick(row["C_upd Dyn E (mJ)"], row["C_qry Dyn E (mJ)"]),
        "rule": "update only (prediction inside update pass)" if single else "update + query",
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--table1", required=True)
    ap.add_argument("--out", required=True,
                    help="markdown output path; a .csv sibling is written too")
    args = ap.parse_args()

    full = pd.read_csv(args.table1)
    t1 = full[full["Precision"] == "fp32"].copy()   # FP16 rows are Extended Data material
    rows = {}
    for _, row in t1.iterrows():
        rows[(row["Method"], row["Device"])] = {**compose(row), "src": row["Exp (upd, qry)"]}

    flat = []   # (key, value, source)

    def put(key, value, source):
        flat.append((key, value, source))

    L = []
    L.append(f"# Number ledger (generated {dt.datetime.now():%Y-%m-%d %H:%M})")
    L.append("")
    L.append(f"Source: `{os.path.relpath(args.table1)}` (Orin Nano, 1-shot seed-10 stream, unified harness). "
             "Generated by `benchmarks/make_ledger.py`; do not edit by hand. Every number in the manuscript "
             "is copied from here with its row id.")
    L.append("")
    L.append("**Composition rule.** Step = cost of producing the prediction for the incoming sample and updating "
             "on its label, each method at its cheapest correct implementation. CLP and Replay compute the "
             "prediction inside the update pass (winner selection; training forward pass), so step = update. "
             "NCM and SLDA do not score the sample during the update, so step = update + query. "
             "Loihi 2: one on-chip pass. FP16 rows and the naive SLDA anchor are Extended Data material.")
    L.append("")

    # ---- Table 1 --------------------------------------------------------
    L.append("## T1. Table 1: per-sample OCL step cost (FP32), accuracy")
    L.append("")
    L.append("| id | Method | System | Acc 1-shot | Acc 25-shot | Latency (ms) | Total E (mJ) | Dyn E (mJ) | rule | source |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    a1, a25 = ACC["CLP-SNN"]
    L.append(f"| T1.0 | CLP-SNN | Loihi 2 INT8 | {a1[0]}+/-{a1[1]} | {a25[0]}+/-{a25[1]} | {LOIHI['lat_ms']} | "
             f"{LOIHI['tot_mJ']} | {LOIHI['dyn_mJ']} | single on-chip pass | round-2 Table 1 |")
    for k in KEYS:
        put(f"T1.0.{k}", LOIHI[k], "round-2 Table 1")
    i = 1
    step = {}
    for m in MAIN_ORDER:
        for dev in ("orin-gpu", "orin-cpu"):
            s = rows[(m, dev)]
            a1, a25 = ACC[m]
            rid = f"T1.{i}"
            step[(m, dev)] = s
            L.append(f"| {rid} | {DISPLAY[m]} | {DEVICE[dev]} FP32 | {a1[0]}+/-{a1[1]} | {a25[0]}+/-{a25[1]} | "
                     f"{r(s['lat_ms'])} | {r(s['tot_mJ'], 1)} | {r(s['dyn_mJ'])} | {s['rule']} | {s['src']} |")
            for k in KEYS:
                put(f"{rid}.{k}", round(s[k], 3), s["src"])
            i += 1
    L.append("")

    # ---- Ratios ---------------------------------------------------------
    L.append("## R. CLP-SNN (Loihi 2) advantage per comparator, with accuracy delta (CLP-SNN minus comparator)")
    L.append("")
    L.append("| id | Comparator | Latency | Total E | Dyn E | dAcc 1-shot (pp) | dAcc 25-shot (pp) |")
    L.append("|---|---|---|---|---|---|---|")
    i = 1
    for m in MAIN_ORDER:
        for dev in ("orin-gpu", "orin-cpu"):
            s = step[(m, dev)]
            rl = s["lat_ms"] / LOIHI["lat_ms"]
            rt = s["tot_mJ"] / LOIHI["tot_mJ"]
            rd = s["dyn_mJ"] / LOIHI["dyn_mJ"]
            d1 = ACC["CLP-SNN"][0][0] - ACC[m][0][0]
            d25 = ACC["CLP-SNN"][1][0] - ACC[m][1][0]
            rid = f"R.{i}"
            L.append(f"| {rid} | {DISPLAY[m]} {DEVICE[dev]} | {ratio(rl)} | {ratio(rt)} | {ratio(rd)} | "
                     f"{d1:+.1f} | {d25:+.1f} |")
            put(f"{rid}.lat", round(rl, 2), "T1")
            put(f"{rid}.tot", round(rt, 1), "T1")
            put(f"{rid}.dyn", round(rd, 1), "T1")
            i += 1
    L.append("")
    L.append("Reading guide: NCM CPU is the iso-latency-class anchor (strict Pareto win on accuracy and energy); "
             "Replay GPU the near-iso-accuracy anchor; SLDA rank-one the high-accuracy point; CLP CPU/GPU the "
             "iso-algorithm co-design row. No algorithmic x hardware decomposition is derived from this table.")
    L.append("")

    # ---- Full pipeline --------------------------------------------------
    L.append("## P. Full pipeline (extractor + step). CLP-SNN pairs with the INT8 extractor")
    L.append("")
    own = {k: LOIHI[k] + FE["INT8"][k] for k in KEYS}
    L.append(f"CLP-SNN + INT8 FE: {r(own['lat_ms'])} ms / {r(own['tot_mJ'], 1)} mJ / {r(own['dyn_mJ'])} mJ dyn (id P.0).")
    for k in KEYS:
        put(f"P.0.{k}", round(own[k], 3), "T1.0 + FE INT8")
    L.append("")
    L.append("| id | Comparator pipeline | Latency (ms) | Total E (mJ) | Dyn E (mJ) | advantage lat / total / dyn |")
    L.append("|---|---|---|---|---|---|")
    i = 1
    for m, dev, fe in [("SLDA-rank1", "orin-gpu", "FP32"), ("SLDA-rank1", "orin-gpu", "INT8"),
                       ("replay", "orin-gpu", "FP32"), ("ncm", "orin-gpu", "FP32"),
                       ("ncm", "orin-cpu", "FP32"), ("ncm", "orin-cpu", "INT8")]:
        s = step[(m, dev)]
        p = {k: s[k] + FE[fe][k] for k in KEYS}
        adv = {k: p[k] / own[k] for k in KEYS}
        rid = f"P.{i}"
        L.append(f"| {rid} | {DISPLAY[m]} {DEVICE[dev]} + {fe} FE | {r(p['lat_ms'])} | {r(p['tot_mJ'], 1)} | "
                 f"{r(p['dyn_mJ'])} | {ratio(adv['lat_ms'])} / {ratio(adv['tot_mJ'])} / {ratio(adv['dyn_mJ'])} |")
        for k in KEYS:
            put(f"{rid}.{k}", round(p[k], 3), f"T1 + FE {fe}")
            put(f"{rid}.adv_{k}", round(adv[k], 2), "P.0")
        i += 1
    L.append("")
    fe_gap = FE["FP32"]["dyn_mJ"] / FE["INT8"]["dyn_mJ"]
    L.append(f"Prose rule: always state the pairing. The FP32-vs-INT8 extractor gap alone is {ratio(fe_gap)} in "
             "dynamic energy, so unpaired full-system ratios are not quoted. Never quote a full-pipeline EDP ratio.")
    L.append("")
    share = {k: LOIHI[k] / own[k] * 100 for k in KEYS}
    L.append(f"Learning-step share of the CLP-SNN pipeline (id P.share): latency {share['lat_ms']:.0f}%, "
             f"total energy {share['tot_mJ']:.1f}%, dynamic energy {share['dyn_mJ']:.2f}%.")
    for k in KEYS:
        put(f"P.share.{k}_pct", round(share[k], 2), "P.0")
    clp_gpu = step[("CLP", "orin-gpu")]
    pipe = clp_gpu["dyn_mJ"] + FE["INT8"]["dyn_mJ"]
    bound = pipe / FE["INT8"]["dyn_mJ"]
    achieved = pipe / own["dyn_mJ"]
    L.append(f"Amdahl (iso-algorithm CLP on GPU, INT8 extractor, dynamic energy; id P.amdahl): CLP-GPU pipeline "
             f"{r(pipe)} mJ, learning share {clp_gpu['dyn_mJ'] / pipe * 100:.0f}%, bound {bound:.2f}x, "
             f"CLP-SNN achieves {achieved:.2f}x.")
    put("P.amdahl.bound", round(bound, 2), "T1.1 + FE INT8")
    put("P.amdahl.achieved", round(achieved, 2), "P.0")
    L.append("")

    # ---- Extended Data primitives --------------------------------------
    L.append("## E. Extended Data: cost primitives (all measured rows, incl. FP16 and the naive anchor)")
    L.append("")
    L.append("| id | Method | System | Prec | upd lat (ms) | qry lat (ms) | upd p99 (ms) | qry p99 (ms) | "
             "upd dyn E (mJ) | qry dyn E (mJ) | in step | source |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    i = 1
    for _, row in full.iterrows():
        m = row["Method"]
        single = m in SINGLE_PASS
        qlat = "within update" if single else r(row["C_qry Latency (ms)"])
        qp99 = "-" if single else r(row["C_qry p99 (ms)"])
        qdyn = "-" if single else r(row["C_qry Dyn E (mJ)"])
        L.append(f"| E.{i} | {DISPLAY.get(m, m)} | {DEVICE[row['Device']]} | {row['Precision'].upper()} | "
                 f"{r(row['C_upd Latency (ms)'])} | {qlat} | {r(row['C_upd p99 (ms)'])} | {qp99} | "
                 f"{r(row['C_upd Dyn E (mJ)'])} | {qdyn} | {'update' if single else 'update + query'} | "
                 f"{row['Exp (upd, qry)']} |")
        rid = f"E.{i}"
        src = row["Exp (upd, qry)"]
        for key, col in (("upd_lat_ms", "C_upd Latency (ms)"), ("upd_p99_ms", "C_upd p99 (ms)"),
                         ("upd_dyn_mJ", "C_upd Dyn E (mJ)"), ("upd_tot_mJ", "C_upd Total E (mJ)")):
            put(f"{rid}.{key}", round(float(row[col]), 3), src)
        if not single:
            for key, col in (("qry_lat_ms", "C_qry Latency (ms)"), ("qry_p99_ms", "C_qry p99 (ms)"),
                             ("qry_dyn_mJ", "C_qry Dyn E (mJ)"), ("qry_tot_mJ", "C_qry Total E (mJ)")):
                put(f"{rid}.{key}", round(float(row[col]), 3), src)
        i += 1
    L.append("")
    L.append("CLP standalone query is not part of the streaming loop; the measured value (exp_2, exp_4) is a "
             "host-sync artifact of the pre-fix predict and is not reported. p99 values are per primitive; "
             "never sum them.")
    L.append("")

    # ---- Open items -----------------------------------------------------
    L.append("## Open items (not numbers yet)")
    L.append("")
    L.append("- State-memory column: compute from end-of-stream prototype counts per protocol before use; "
             "not in this ledger.")
    L.append("- Loihi window contents (supervisor round trip): pending Intel confirmation; affects wording only.")
    L.append("- Compiled-NCM control and fixed CLP query: add rows here if the re-runs arrive; nothing else changes.")
    L.append("- Naive-SLDA accuracy (54.4 / 95.7) is the Hayes shrinkage variant; the SI anchor row reports cost only.")

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    pd.DataFrame(flat, columns=["key", "value", "source"]).to_csv(
        os.path.splitext(args.out)[0] + ".csv", index=False)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
